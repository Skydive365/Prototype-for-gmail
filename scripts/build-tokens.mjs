// Turns tokens/tokens.json (exported from Figma) into app/tokens.css.
// Run with: npm run tokens
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const { collections, textStyles } = JSON.parse(readFileSync(root + "tokens/tokens.json", "utf8"));

// "color/text/primary" -> "--color-text-primary"
const cssVar = (name) => "--" + name.replace(/\//g, "-");

// Figma stores weights as font-style names; CSS needs numbers.
const WEIGHTS = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700 };

function formatValue(name, { type, value, alias }) {
  if (alias) return `var(${cssVar(alias)})`;
  if (type === "COLOR") return value;
  if (name.startsWith("font/family/")) return `var(--font-roboto), "${value}", sans-serif`;
  if (name.startsWith("font/weight/")) return String(WEIGHTS[value] ?? 400);
  if (type === "FLOAT") return `${value}px`;
  return String(value);
}

function block(selector, vars, comment) {
  const lines = Object.entries(vars).map(([name, token]) => `  ${cssVar(name)}: ${formatValue(name, token)};`);
  return `/* ${comment} */\n${selector} {\n${lines.join("\n")}\n}\n`;
}

const textStyleCss = Object.entries(textStyles).map(([name, s]) => {
  const props = [
    `font-family: var(${cssVar(s.fontFamily)});`,
    `font-weight: var(${cssVar(s.fontWeight)});`,
    `font-size: var(${cssVar(s.fontSize)});`,
    `line-height: var(${cssVar(s.lineHeight)});`,
    `letter-spacing: var(${cssVar(s.letterSpacing)});`,
  ];
  return `.text-${name.replace(/\//g, "-")} {\n  ${props.join("\n  ")}\n}`;
});

const css = [
  "/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n",
  block(":root", collections.Primitives.variables, "Primitives: raw values, never used directly by components (except space/radius)"),
  block(":root", collections.Typography.variables, "Typography"),
  block(":root,\n[data-theme=\"light\"]", collections.Semantic.variables, "Semantic, Light (Figma collection: Semantic)"),
  block("[data-theme=\"dark\"]", collections["Semantic Dark"].variables, "Semantic, Dark (Figma collection: Semantic Dark)"),
  "/* Text styles (Figma local text styles) */",
  textStyleCss.join("\n\n"),
  "",
].join("\n");

writeFileSync(root + "app/tokens.css", css);
console.log("app/tokens.css written");
